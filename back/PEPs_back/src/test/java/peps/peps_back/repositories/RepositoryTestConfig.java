package peps.peps_back.repositories;

import java.util.HashMap;
import java.util.Map;
import javax.persistence.EntityManagerFactory;
import javax.sql.DataSource;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.orm.jpa.JpaTransactionManager;
import org.springframework.orm.jpa.LocalContainerEntityManagerFactoryBean;
import org.springframework.orm.jpa.vendor.EclipseLinkJpaVendorAdapter;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;

/**
 * Spring test configuration for repository integration tests.
 * <p>
 * Mirrors the production JPA setup declared in {@code applicationContext.xml}
 * (same persistence unit, EclipseLink provider and Spring Data repositories), but
 * replaces the PostgreSQL datasource with an H2 in-memory database. The schema is
 * generated from the JPA entities at startup and discarded when the JVM stops.
 *
 * @author María Paz Muñoz
 * @version 2.0
 */
@Configuration
@EnableTransactionManagement
@EnableJpaRepositories(basePackages = "peps.peps_back.repositories")
public class RepositoryTestConfig {

    /**
     * JDBC URL of the in-memory database.
     * <ul>
     *   <li>{@code MODE=LEGACY}: accepts the {@code IDENTITY} column type and {@code IDENTITY()}
     *       function generated by EclipseLink 2.7's H2 platform, removed from H2 2.x by default.</li>
     *   <li>{@code DB_CLOSE_DELAY=-1}: keeps the database alive between connections.</li>
     *   <li>{@code INIT}: creates the {@code peps} schema expected by the persistence unit
     *       and a {@code JSONB} domain, since that PostgreSQL type does not exist in H2.</li>
     * </ul>
     */
    private static final String H2_URL = "jdbc:h2:mem:peps_test;MODE=LEGACY;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE;"
            + "INIT=CREATE SCHEMA IF NOT EXISTS peps\\;CREATE DOMAIN IF NOT EXISTS JSONB AS VARCHAR";

    /**
     * Provides the H2 in-memory datasource used instead of PostgreSQL.
     *
     * @return the test datasource
     */
    @Bean
    public DataSource dataSource() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource();
        dataSource.setDriverClassName("org.h2.Driver");
        dataSource.setUrl(H2_URL);
        dataSource.setUsername("sa");
        dataSource.setPassword("");
        return dataSource;
    }

    /**
     * Builds the entity manager factory from the production persistence unit, overriding
     * the DDL generation so that tables are created from the entities for each test run.
     *
     * @param dataSource the test datasource
     * @return the configured entity manager factory bean
     */
    @Bean
    public LocalContainerEntityManagerFactoryBean entityManagerFactory(DataSource dataSource) {
        LocalContainerEntityManagerFactoryBean emf = new LocalContainerEntityManagerFactoryBean();
        emf.setDataSource(dataSource);
        emf.setPersistenceUnitName("peps.peps_back.0PU");
        emf.setJpaVendorAdapter(new EclipseLinkJpaVendorAdapter());

        Map<String, Object> properties = new HashMap<>();
        properties.put("eclipselink.ddl-generation", "drop-and-create-tables");
        properties.put("eclipselink.ddl-generation.output-mode", "database");
        properties.put("eclipselink.logging.level", "WARNING");
        emf.setJpaPropertyMap(properties);
        return emf;
    }

    /**
     * Provides the JPA transaction manager so that each test can run in a transaction
     * that is rolled back afterwards.
     *
     * @param entityManagerFactory the entity manager factory
     * @return the transaction manager
     */
    @Bean
    public PlatformTransactionManager transactionManager(EntityManagerFactory entityManagerFactory) {
        return new JpaTransactionManager(entityManagerFactory);
    }
}
