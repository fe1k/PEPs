package peps.peps_back.services;

import java.time.LocalDateTime;
import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import peps.peps_back.domain.Interaction;
import peps.peps_back.domain.IoTModule;
import peps.peps_back.domain.Sound;
import peps.peps_back.repositories.InteractionRepository;
import peps.peps_back.repositories.IoTModuleRepository;
import peps.peps_back.repositories.SoundRepository;

/**
 * Service layer responsible for recording, processing, and querying physical
 * animal-device interaction events generated by {@link IoTModule} hardware
 * and optionally associated with triggered {@link Sound} assets.
 *
 * @author Franco Valdebenito
 * @version 1.0
 */
@Service
public class InteractionService {

    private static final Logger LOGGER = LoggerFactory.getLogger(InteractionService.class);

    public static final int MAX_INTERACTION_TYPE_LENGTH = 50;

    private final InteractionRepository interactionRepository;
    private final IoTModuleRepository moduleRepository;
    private final SoundRepository soundRepository;

    /**
     * Constructs an {@code InteractionService} with its required persistence repositories.
     *
     * @param interactionRepository repository managing {@link Interaction} events
     * @param moduleRepository      repository managing {@link IoTModule} entities
     * @param soundRepository       repository managing {@link Sound} entities
     */
    @Autowired
    public InteractionService(
            InteractionRepository interactionRepository,
            IoTModuleRepository moduleRepository,
            SoundRepository soundRepository) {
        this.interactionRepository = interactionRepository;
        this.moduleRepository = moduleRepository;
        this.soundRepository = soundRepository;
    }

    /**
     * Retrieves a paginated list of recorded interactions ordered from most recent to oldest.
     *
     * @param page zero-based page index (must be non-negative)
     * @param size number of records per page (must be strictly positive)
     * @return a {@link Page} of {@link Interaction} entities
     * @throws IllegalArgumentException if {@code page < 0} or {@code size <= 0}
     */
    @Transactional(readOnly = true)
    public Page<Interaction> getInteractions(int page, int size) {
        if (page < 0) {
            throw new IllegalArgumentException("Page index must be non-negative");
        }
        if (size <= 0) {
            throw new IllegalArgumentException("Page size must be a positive integer");
        }

        Pageable pageable = PageRequest.of(page, size, Sort.by(Sort.Direction.DESC, "triggeredAt"));
        return interactionRepository.findAll(pageable);
    }

    /**
     * Retrieves all interactions recorded by a specific IoT module within a time window.
     *
     * @param moduleId the primary key of the target {@link IoTModule}
     * @param start    inclusive start timestamp of the query window
     * @param end      inclusive end timestamp of the query window
     * @return a list of matching {@link Interaction} records
     * @throws IllegalArgumentException if {@code moduleId} is invalid or timestamps are null/inverted
     */
    @Transactional(readOnly = true)
    public List<Interaction> getInteractionsByModuleAndPeriod(
            Integer moduleId,
            LocalDateTime start,
            LocalDateTime end) {
        validatePositiveId(moduleId, "Module ID");
        if (start == null || end == null) {
            throw new IllegalArgumentException("Start and end timestamps must not be null");
        }
        if (start.isAfter(end)) {
            throw new IllegalArgumentException("Start timestamp must not be after end timestamp");
        }

        return interactionRepository.findByModule_ModuleIdAndTriggeredAtBetween(moduleId, start, end);
    }

    /**
     * Retrieves all interactions recorded across IoT modules assigned to a given species.
     *
     * @param speciesId the primary key of the target species
     * @return a list of {@link Interaction} records associated with the species
     * @throws IllegalArgumentException if {@code speciesId} is invalid
     */
    @Transactional(readOnly = true)
    public List<Interaction> getInteractionsBySpecies(Integer speciesId) {
        validatePositiveId(speciesId, "Species ID");
        return interactionRepository.findByModule_Species_SpeciesId(speciesId);
    }

    /**
     * Validates, resolves managed associations, and persists a pre-constructed {@link Interaction}.
     *
     * <p>If {@code triggeredAt} is not set on the incoming entity, the current timestamp is assigned.
     *
     * @param interaction the {@link Interaction} instance to persist
     * @return the newly persisted {@link Interaction} entity
     * @throws IllegalArgumentException if the interaction payload or referenced entities are invalid
     */
    @Transactional
    public Interaction recordInteraction(Interaction interaction) {
        if (interaction == null) {
            throw new IllegalArgumentException("Interaction must not be null");
        }

        String normalizedType = validateAndNormalizeType(interaction.getInteractionType());
        interaction.setInteractionType(normalizedType);

        if (interaction.getModule() == null || interaction.getModule().getModuleId() == null) {
            throw new IllegalArgumentException("Interaction must reference a valid IoT module ID");
        }

        Integer moduleId = interaction.getModule().getModuleId();
        validatePositiveId(moduleId, "Module ID");
        IoTModule managedModule = moduleRepository.findById(moduleId)
                .orElseThrow(() -> new IllegalArgumentException("IoT module not found with ID: " + moduleId));
        interaction.setModule(managedModule);

        if (interaction.getSound() != null) {
            Integer soundId = interaction.getSound().getSoundId();
            validatePositiveId(soundId, "Sound ID");
            Sound managedSound = soundRepository.findById(soundId)
                    .orElseThrow(() -> new IllegalArgumentException("Sound not found with ID: " + soundId));
            interaction.setSound(managedSound);
        }

        if (interaction.getTriggeredAt() == null) {
            interaction.setTriggeredAt(LocalDateTime.now());
        }

        Interaction saved = interactionRepository.save(interaction);
        LOGGER.info("Recorded interaction '{}' (id={}, moduleId={}, soundId={})",
                saved.getInteractionType(),
                saved.getInteractionId(),
                managedModule.getModuleId(),
                saved.getSound() != null ? saved.getSound().getSoundId() : null);
        return saved;
    }

    /**
     * Processes a telemetry trigger sent by an ESP32 module, creating and persisting a new
     * {@link Interaction} linked to the module and, optionally, the played {@link Sound}.
     *
     * @param moduleId the primary key of the {@link IoTModule} that detected the event
     * @param soundId  the primary key of the triggered {@link Sound}, or {@code null} for silent events
     * @param type     the physical interaction category (e.g., {@code "ROPE_PULL"}, {@code "BUTTON"})
     * @return the newly persisted {@link Interaction} entity
     * @throws IllegalArgumentException if any identifier or interaction type is invalid or not found
     */
    @Transactional
    public Interaction processIoTTrigger(Integer moduleId, Integer soundId, String type) {
        validatePositiveId(moduleId, "Module ID");
        String normalizedType = validateAndNormalizeType(type);

        IoTModule module = moduleRepository.findById(moduleId)
                .orElseThrow(() -> new IllegalArgumentException("IoT module not found with ID: " + moduleId));

        Sound sound = null;
        if (soundId != null) {
            validatePositiveId(soundId, "Sound ID");
            sound = soundRepository.findById(soundId)
                    .orElseThrow(() -> new IllegalArgumentException("Sound not found with ID: " + soundId));
        }

        Interaction interaction = new Interaction(normalizedType, module, sound);
        interaction.setTriggeredAt(LocalDateTime.now());

        Interaction saved = interactionRepository.save(interaction);
        LOGGER.info("Processed IoT trigger '{}' (id={}, module='{}', soundId={})",
                saved.getInteractionType(),
                saved.getInteractionId(),
                module.getName(),
                soundId);
        return saved;
    }

    /**
     * Validates and trims the interaction type label against null/blank and database length bounds.
     */
    private String validateAndNormalizeType(String type) {
        if (type == null || type.isBlank()) {
            throw new IllegalArgumentException("Interaction type must not be null or blank");
        }
        String trimmed = type.trim();
        if (trimmed.length() > MAX_INTERACTION_TYPE_LENGTH) {
            throw new IllegalArgumentException(
                    "Interaction type must not exceed " + MAX_INTERACTION_TYPE_LENGTH + " characters");
        }
        return trimmed;
    }

    /**
     * Validates that an entity identifier is non-null and strictly positive.
     */
    private void validatePositiveId(Integer id, String fieldName) {
        if (id == null || id <= 0) {
            throw new IllegalArgumentException(fieldName + " must be a positive integer");
        }
    }
}